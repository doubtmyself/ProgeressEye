def t(key: str) -> str:
    """현재 언어로 번역된 문자열을 반환한다.

    키가 없으면 키 자체를 반환한다.
    """
    return TRANSLATIONS.get(_current_lang, {}).get(key, key)


def set_language(lang: str) -> None:
    """표시 언어를 변경한다."""
    global _current_lang  # noqa: PLW0603
    _current_lang = lang


def get_language() -> str:
    """현재 언어 코드를 반환한다."""
    return _current_lang
